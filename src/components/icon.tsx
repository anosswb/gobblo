export type IconName = keyof typeof MAP;

/** The SF Symbol behind an icon name (iOS widgets and Live Activities draw it natively). */
export const sfSymbol = (name: IconName): string => MAP[name][0];

const STROKE: Record<'regular' | 'semibold' | 'bold', number> = { regular: 1.75, semibold: 2, bold: 2.4 };

export function Icon({
  name,
  size = 22,
  color,
  weight = 'semibold',
}: {
  name: IconName;
  size?: number;
  color: string;
  weight?: 'regular' | 'semibold' | 'bold';
  /** kept for older call sites; Lucide is a line set */
  filled?: boolean;
}) {
  const [sf, Line] = MAP[name];
  if (Platform.OS === 'ios') {
    return <SymbolView name={sf as never} size={size} tintColor={color} weight={weight as SymbolWeight} resizeMode="scaleAspectFit" style={{ width: size, height: size }} />;
  }
  return <Line size={size} color={color} strokeWidth={STROKE[weight]} />;
}
