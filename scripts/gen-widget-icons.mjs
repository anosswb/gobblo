// Builds src/widgets/icon-paths.ts: every Icon name (src/components/icon.tsx) → its Lucide SVG
// markup, so Android home-screen widgets (which can't run react-native-svg) can draw the same icons.
// Run after adding an icon: node scripts/gen-widget-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('src/components/icon.tsx', 'utf8');
const files = Object.fromEntries([...src.matchAll(/import (\w+) from 'lucide-react-native\/icons\/([\w-]+)';/g)].map((m) => [m[1], m[2]]));
const entries = [...src.matchAll(/^\s+(\w+): \['[^']*', (\w+)\],/gm)].map((m) => [m[1], m[2]]);

const attr = (o) => Object.entries(o).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ');
const out = {};
for (const [name, comp] of entries) {
  const file = files[comp];
  if (!file) throw new Error(`no import for ${comp}`);
  let text = readFileSync(`node_modules/lucide-react-native/dist/esm/icons/${file}.mjs`, 'utf8');
  // aliases re-export another file
  for (let alias = text.match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/); alias; alias = text.match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/)) {
    text = readFileSync(`node_modules/lucide-react-native/dist/esm/icons/${alias[1]}.mjs`, 'utf8');
  }
  const m = text.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!m) throw new Error(`can't read ${file}`);
  const { node } = Function(`return ${m[1]}`)();
  out[name] = node.map(([tag, a]) => `<${tag} ${attr(a)}/>`).join('');
}

const lines = Object.entries(out).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
writeFileSync(
  'src/widgets/icon-paths.ts',
  `// GENERATED by scripts/gen-widget-icons.mjs from src/components/icon.tsx (Lucide, ISC licence). Do not edit.\nimport type { IconName } from '@/components/icon';\n\nexport const ICON_PATHS: Record<IconName, string> = {\n${lines}\n};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons`);
